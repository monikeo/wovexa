/**
 * Semantic editing commands (spec ED2-14, §27.2). Every user edit, from either the 2D or
 * the 3D view, becomes one of these. A command is a pure Immer recipe plus a label for the
 * history panel; the history module turns it into undoable patches.
 * Commands must be deterministic: generate ids before building the command, never inside it.
 */
import type {
  ArtworkLayer,
  Colorway,
  DesignDocument,
  GarmentPart,
  LayerContent,
  LayerStyle,
  LayerTransform,
  PrintMethod,
  ZoneId,
} from './schema';

export interface Command {
  label: string;
  recipe: (draft: DesignDocument) => void;
}

export function addLayer(zoneId: ZoneId, layer: ArtworkLayer, index?: number): Command {
  return {
    label: `Add ${layer.name}`,
    recipe: (d) => {
      const zone = d.zones[zoneId];
      zone.layers[layer.id] = layer;
      const at = index === undefined ? zone.orderedLayerIds.length : Math.max(0, Math.min(index, zone.orderedLayerIds.length));
      zone.orderedLayerIds.splice(at, 0, layer.id);
    },
  };
}

export function removeLayers(zoneId: ZoneId, layerIds: string[]): Command {
  return {
    label: layerIds.length === 1 ? 'Delete layer' : `Delete ${layerIds.length} layers`,
    recipe: (d) => {
      const zone = d.zones[zoneId];
      for (const id of layerIds) delete zone.layers[id];
      zone.orderedLayerIds = zone.orderedLayerIds.filter((id) => !layerIds.includes(id));
    },
  };
}

/** Duplicate layers. `newIds` maps each source id to its copy's id, generated by the caller. */
export function duplicateLayers(zoneId: ZoneId, newIds: Record<string, string>, offsetMm = 6): Command {
  return {
    label: Object.keys(newIds).length === 1 ? 'Duplicate layer' : 'Duplicate layers',
    recipe: (d) => {
      const zone = d.zones[zoneId];
      for (const [sourceId, copyId] of Object.entries(newIds)) {
        const source = zone.layers[sourceId];
        if (!source) continue;
        const copy: ArtworkLayer = JSON.parse(JSON.stringify(source));
        copy.id = copyId;
        copy.name = `${source.name} copy`;
        copy.locked = false;
        copy.transform.centerXmm += offsetMm;
        copy.transform.centerYmm += offsetMm;
        zone.layers[copyId] = copy;
        const at = zone.orderedLayerIds.indexOf(sourceId);
        zone.orderedLayerIds.splice(at + 1, 0, copyId);
      }
    },
  };
}

export function updateTransforms(zoneId: ZoneId, changes: Record<string, Partial<LayerTransform>>, label = 'Move'): Command {
  return {
    label,
    recipe: (d) => {
      const zone = d.zones[zoneId];
      for (const [id, patch] of Object.entries(changes)) {
        const layer = zone.layers[id];
        if (layer) Object.assign(layer.transform, patch);
      }
    },
  };
}

export interface LayerPatch {
  name?: string;
  visible?: boolean;
  locked?: boolean;
  style?: Partial<LayerStyle>;
  /** Fields of the existing content kind. Changing the kind is not allowed. */
  content?: Partial<LayerContent>;
  transform?: Partial<LayerTransform>;
}

export function updateLayer(zoneId: ZoneId, layerId: string, patch: LayerPatch, label = 'Edit layer'): Command {
  return {
    label,
    recipe: (d) => {
      const layer = d.zones[zoneId].layers[layerId];
      if (!layer) return;
      if (patch.name !== undefined) layer.name = patch.name;
      if (patch.visible !== undefined) layer.visible = patch.visible;
      if (patch.locked !== undefined) layer.locked = patch.locked;
      if (patch.style) Object.assign(layer.style, patch.style);
      if (patch.transform) Object.assign(layer.transform, patch.transform);
      if (patch.content) {
        const { kind, ...rest } = patch.content as Partial<LayerContent> & { kind?: string };
        if (kind === undefined || kind === layer.content.kind) Object.assign(layer.content, rest);
      }
    },
  };
}

/** Move a layer to a new index in the zone's stacking order (0 = bottom). */
export function reorderLayer(zoneId: ZoneId, layerId: string, toIndex: number): Command {
  return {
    label: 'Reorder layers',
    recipe: (d) => {
      const order = d.zones[zoneId].orderedLayerIds;
      const from = order.indexOf(layerId);
      if (from < 0) return;
      order.splice(from, 1);
      order.splice(Math.max(0, Math.min(toIndex, order.length)), 0, layerId);
    },
  };
}

export function setPrintMethod(zoneId: ZoneId, method: PrintMethod): Command {
  return { label: 'Change print method', recipe: (d) => void (d.zones[zoneId].printMethod = method) };
}

export function setColorwayPart(colorwayId: string, part: GarmentPart, hex: string): Command {
  return {
    label: 'Change garment colour',
    recipe: (d) => {
      const cw = d.colorways.find((c) => c.id === colorwayId);
      if (cw) cw.parts[part] = hex.toUpperCase();
    },
  };
}

export function addColorway(colorway: Colorway, makeActive = true): Command {
  return {
    label: `Add colourway ${colorway.name}`,
    recipe: (d) => {
      d.colorways.push(colorway);
      if (makeActive) d.activeColorwayId = colorway.id;
    },
  };
}

export function removeColorway(colorwayId: string): Command {
  return {
    label: 'Delete colourway',
    recipe: (d) => {
      if (d.colorways.length <= 1) return;
      d.colorways = d.colorways.filter((c) => c.id !== colorwayId);
      if (d.activeColorwayId === colorwayId) d.activeColorwayId = d.colorways[0].id;
    },
  };
}

export function renameColorway(colorwayId: string, name: string): Command {
  return {
    label: 'Rename colourway',
    recipe: (d) => {
      const cw = d.colorways.find((c) => c.id === colorwayId);
      if (cw) cw.name = name;
    },
  };
}

export function setActiveColorway(colorwayId: string): Command {
  return { label: 'Switch colourway', recipe: (d) => void (d.activeColorwayId = colorwayId) };
}

export function setGarmentSize(sizeCode: string): Command {
  return { label: `Size ${sizeCode}`, recipe: (d) => void (d.garment.sizeCode = sizeCode) };
}

export function setFabricPreset(presetId: string): Command {
  return { label: 'Change fabric', recipe: (d) => void (d.garment.fabricPresetId = presetId) };
}

export function renameDocument(title: string): Command {
  return { label: 'Rename project', recipe: (d) => void (d.title = title) };
}

export function setNotes(notes: string): Command {
  return { label: 'Edit notes', recipe: (d) => void (d.notes = notes) };
}
