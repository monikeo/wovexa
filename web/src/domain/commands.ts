export interface Command {
  label: string;
  recipe: (draft: DesignDocument) => void;
  /** Rapid repeats with the same key (slider drags, key repeats) share one undo step. */
  coalesceKey?: string;
}

/** Mark a command as part of a continuous gesture. */
export function coalescing(command: Command, key: string): Command {
  return { ...command, coalesceKey: key };
}

/** Several commands as one undo step. */
export function batch(label: string, commands: Command[]): Command {
  return {
    label,
    recipe: (d) => {
      for (const c of commands) c.recipe(d);
    },
  };
}

/** The layers of a print zone, a design area or a lockup's board, in the draft being edited. */
function stackOf(d: DesignDocument, id: ArtboardId): (LayerStack & { printMethod?: PrintMethod }) | undefined {
  if (isLockupId(id)) return d.lockups?.items[id];
  return isAreaId(id) ? d.areas?.items[id] : d.zones[id];
}

// ---- Stacking helpers: grouped layers always move as one contiguous block ----

function blockOf(zone: LayerStack, layerId: string): string[] {
  const group = zone.layers[layerId]?.groupId;
  return group ? zone.orderedLayerIds.filter((id) => zone.layers[id]?.groupId === group) : [layerId];
}

function removeBlock(order: string[], block: string[]) {
  for (const id of block) order.splice(order.indexOf(id), 1);
}

export function addLayer(zoneId: ArtboardId, layer: ArtworkLayer, index?: number): Command {
  return {
    label: `Add ${layer.name}`,
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone) return;
      zone.layers[layer.id] = layer;
      const at = index === undefined ? zone.orderedLayerIds.length : Math.max(0, Math.min(index, zone.orderedLayerIds.length));
      zone.orderedLayerIds.splice(at, 0, layer.id);
    },
  };
}

/** Add ready-made layers (pasted, say) on top of a zone or design area, in their order, as one step. */
export function addLayers(zoneId: ArtboardId, layers: ArtworkLayer[], label: string): Command {
  return {
    label,
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone) return;
      for (const layer of layers) {
        zone.layers[layer.id] = layer;
        zone.orderedLayerIds.push(layer.id);
      }
    },
  };
}

export function removeLayers(zoneId: ArtboardId, layerIds: string[]): Command {
  return {
    label: layerIds.length === 1 ? 'Delete layer' : `Delete ${layerIds.length} layers`,
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone) return;
      for (const id of layerIds) delete zone.layers[id];
      zone.orderedLayerIds = zone.orderedLayerIds.filter((id) => !layerIds.includes(id));
    },
  };
}

/**
 * Duplicate layers. `newIds` maps each source id to its copy's id, generated by the caller.
 * Copies land together above the highest source. A whole group duplicated becomes a new
 * group; a single member duplicated on its own becomes an ungrouped layer.
 */
export function duplicateLayers(zoneId: ArtboardId, newIds: Record<string, string>, offsetMm = 6): Command {
  return {
    label: Object.keys(newIds).length === 1 ? 'Duplicate layer' : 'Duplicate layers',
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone) return;
      const sources = zone.orderedLayerIds.filter((id) => newIds[id] && zone.layers[id]);
      if (!sources.length) return;
      const groupCopies = new Map<string, string>();
      for (const id of sources) {
        const g = zone.layers[id].groupId;
        if (!g || groupCopies.has(g)) continue;
        const members = zone.orderedLayerIds.filter((x) => zone.layers[x].groupId === g);
        if (members.every((m) => newIds[m])) groupCopies.set(g, `g-${newIds[members[0]]}`);
      }
      const top = Math.max(...sources.map((id) => {
        const block = blockOf(zone, id);
        return zone.orderedLayerIds.indexOf(block[block.length - 1]);
      }));
      const copies: string[] = [];
      for (const sourceId of sources) {
        const source = zone.layers[sourceId];
        const copy: ArtworkLayer = JSON.parse(JSON.stringify(source));
        copy.id = newIds[sourceId];
        copy.name = `${source.name} copy`;
        copy.locked = false;
        copy.transform.centerXmm += offsetMm;
        copy.transform.centerYmm += offsetMm;
        const g = source.groupId ? groupCopies.get(source.groupId) : undefined;
        if (g) copy.groupId = g;
        else delete copy.groupId;
        zone.layers[copy.id] = copy;
        copies.push(copy.id);
      }
      zone.orderedLayerIds.splice(top + 1, 0, ...copies);
    },
  };
}

export function updateTransforms(zoneId: ArtboardId, changes: Record<string, Partial<LayerTransform>>, label = 'Move'): Command {
  return {
    label,
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone) return;
      for (const [id, patch] of Object.entries(changes)) {
        const layer = zone.layers[id];
        if (layer) Object.assign(layer.transform, patch);
      }
    },
  };
}

export interface LayerPatch {
  name?: string;
  visible?: boolean;
  locked?: boolean;
  /** Clip to the layer below, or release the clip. */
  clip?: boolean;
  style?: Partial<LayerStyle>;
  /** Fields of the existing content kind. Changing the kind is not allowed. */
  content?: Partial<LayerContent>;
  transform?: Partial<LayerTransform>;
}

export function updateLayer(zoneId: ArtboardId, layerId: string, patch: LayerPatch, label = 'Edit layer'): Command {
  return {
    label,
    recipe: (d) => {
      const layer = stackOf(d, zoneId)?.layers[layerId];
      if (!layer) return;
      if (patch.name !== undefined) layer.name = patch.name;
      if (patch.visible !== undefined) layer.visible = patch.visible;
      if (patch.locked !== undefined) layer.locked = patch.locked;
      if (patch.clip === true) layer.clip = true;
      else if (patch.clip === false) delete layer.clip;
      if (patch.style) {
        // An explicit undefined removes an optional style field (e.g. switching distress off).
        for (const [k, v] of Object.entries(patch.style)) {
          if (v === undefined) delete (layer.style as Record<string, unknown>)[k];
          else (layer.style as Record<string, unknown>)[k] = v;
        }
      }
      if (patch.transform) Object.assign(layer.transform, patch.transform);
      if (patch.content) {
        const { kind, ...rest } = patch.content as Partial<LayerContent> & { kind?: string };
        if (kind === undefined || kind === layer.content.kind) {
          for (const [k, v] of Object.entries(rest)) {
            if (v === undefined) delete (layer.content as Record<string, unknown>)[k];
            else (layer.content as Record<string, unknown>)[k] = v;
          }
        }
      }
    },
  };
}

/** Move a layer (or its whole group) to the bottom (0) or top (any index ≥ length − 1) of the stack. */
export function reorderLayer(zoneId: ArtboardId, layerId: string, toIndex: number): Command {
  return {
    label: 'Reorder layers',
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone) return;
      if (!zone.layers[layerId]) return;
      const block = blockOf(zone, layerId);
      removeBlock(zone.orderedLayerIds, block);
      const at = Math.max(0, Math.min(toIndex, zone.orderedLayerIds.length));
      zone.orderedLayerIds.splice(at, 0, ...block);
    },
  };
}

/** Move a layer (or its group) one step up (+1) or down (−1), past the neighbouring layer or group. */
export function moveLayerBy(zoneId: ArtboardId, layerId: string, delta: 1 | -1): Command {
  return {
    label: delta > 0 ? 'Bring forward' : 'Send backward',
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone) return;
      const order = zone.orderedLayerIds;
      if (!zone.layers[layerId]) return;
      const block = blockOf(zone, layerId);
      const start = order.indexOf(block[0]);
      const end = order.indexOf(block[block.length - 1]);
      if (delta > 0 && end < order.length - 1) {
        const neighbour = blockOf(zone, order[end + 1]);
        removeBlock(order, block);
        order.splice(order.indexOf(neighbour[neighbour.length - 1]) + 1, 0, ...block);
      } else if (delta < 0 && start > 0) {
        const neighbour = blockOf(zone, order[start - 1]);
        removeBlock(order, block);
        order.splice(order.indexOf(neighbour[0]), 0, ...block);
      }
    },
  };
}

/** Group layers. Members are gathered into one block at the position of the topmost member. */
export function groupLayers(zoneId: ArtboardId, layerIds: string[], groupId: string): Command {
  return {
    label: 'Group',
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone) return;
      const members = zone.orderedLayerIds.filter((id) => layerIds.includes(id) || (zone.layers[id]?.groupId && layerIds.some((x) => zone.layers[x]?.groupId === zone.layers[id].groupId)));
      if (members.length < 2) return;
      const topIndex = Math.max(...members.map((id) => zone.orderedLayerIds.indexOf(id)));
      const above = zone.orderedLayerIds.slice(topIndex + 1);
      const below = zone.orderedLayerIds.slice(0, topIndex + 1).filter((id) => !members.includes(id));
      zone.orderedLayerIds = [...below, ...members, ...above];
      for (const id of members) zone.layers[id].groupId = groupId;
    },
  };
}

export function ungroupLayers(zoneId: ArtboardId, layerIds: string[]): Command {
  return {
    label: 'Ungroup',
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone) return;
      const groups = new Set(layerIds.map((id) => zone.layers[id]?.groupId).filter(Boolean));
      for (const layer of Object.values(zone.layers)) if (layer.groupId && groups.has(layer.groupId)) delete layer.groupId;
    },
  };
}

/** Replace a print area's ruler guides (none removes them). */
export function setGuides(zoneId: ArtboardId, guides: { x: number[]; y: number[] } | undefined, label = 'Move guide'): Command {
  return {
    label,
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone) return;
      if (guides && (guides.x.length || guides.y.length)) zone.guides = { x: [...guides.x], y: [...guides.y] };
      else delete zone.guides;
    },
  };
}

export function setPrintMethod(zoneId: ArtboardId, method: PrintMethod): Command {
  return {
    label: 'Change print method',
    recipe: (d) => {
      // A lockup prints by the method of wherever it is placed.
      if (isLockupId(zoneId)) return;
      const zone = stackOf(d, zoneId);
      if (zone) zone.printMethod = method;
    },
  };
}

// ---- Reusable lockups (spec ED2-12) ----

/**
 * Make a lockup of layers on an artboard: they move onto the lockup's own board and `placement`
 * takes their place, at the stack position of the topmost of them. One undo step.
 */
export function makeLockup(zoneId: ArtboardId, layerIds: string[], lockup: Lockup, placement: Placement): Command {
  return {
    label: `Make lockup ${lockup.name}`,
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone || isLockupId(zoneId)) return;
      const at = Math.max(...layerIds.map((id) => zone.orderedLayerIds.indexOf(id)));
      if (at < 0) return;
      const below = zone.orderedLayerIds.slice(0, at + 1).filter((id) => !layerIds.includes(id)).length;
      for (const id of layerIds) delete zone.layers[id];
      zone.orderedLayerIds = zone.orderedLayerIds.filter((id) => !layerIds.includes(id));
      d.lockups ??= { orderedIds: [], items: {} };
      d.lockups.items[lockup.id] = structuredClone(lockup);
      if (!d.lockups.orderedIds.includes(lockup.id)) d.lockups.orderedIds.push(lockup.id);
      zone.layers[placement.id] = structuredClone(placement);
      zone.orderedLayerIds.splice(below, 0, placement.id);
    },
  };
}

/** Add a lockup (built by the caller) to the design, unless it is there already. */
export function addLockup(lockup: Lockup): Command {
  return {
    label: `Add lockup ${lockup.name}`,
    recipe: (d) => {
      d.lockups ??= { orderedIds: [], items: {} };
      if (d.lockups.items[lockup.id]) return;
      d.lockups.items[lockup.id] = structuredClone(lockup);
      d.lockups.orderedIds.push(lockup.id);
    },
  };
}

export function renameLockup(lockupId: LockupId, name: string): Command {
  return {
    label: 'Rename lockup',
    recipe: (d) => {
      const lockup = d.lockups?.items[lockupId];
      if (lockup && name.trim()) lockup.name = name.trim().slice(0, 60);
    },
  };
}

/** Delete a lockup no longer placed anywhere. */
export function removeLockup(lockupId: LockupId, name = 'lockup'): Command {
  return {
    label: `Delete ${name}`,
    recipe: (d) => {
      if (!d.lockups?.items[lockupId] || placementsOf(d, lockupId).length) return;
      delete d.lockups.items[lockupId];
      d.lockups.orderedIds = d.lockups.orderedIds.filter((id) => id !== lockupId);
      if (!d.lockups.orderedIds.length) delete d.lockups;
    },
  };
}

/**
 * Fit a lockup's board round its artwork after editing it, with every placement's box changed to
 * match so nothing on the garment moves.
 */
export function fitLockupBoard(lockupId: LockupId): Command {
  return {
    label: 'Fit lockup to its artwork',
    recipe: (d) => {
      const lockup = d.lockups?.items[lockupId];
      if (!lockup) return;
      const fit = boardFit(lockup);
      if (!fit) return;
      for (const layer of Object.values(lockup.layers)) {
        layer.transform.centerXmm -= fit.x;
        layer.transform.centerYmm -= fit.y;
      }
      if (lockup.guides) lockup.guides = { x: lockup.guides.x.map((x) => x - fit.x), y: lockup.guides.y.map((y) => y - fit.y) };
      lockup.widthMm = fit.w;
      lockup.heightMm = fit.h;
      for (const site of placementsOf(d, lockupId)) {
        const layer = site.artboard === null ? d.projections.layers[site.layerId] : stackOf(d, site.artboard)?.layers[site.layerId];
        if (!layer) continue;
        const next = croppedTransform({ ...layer.transform, centerXmm: 0, centerYmm: 0 } as LayerTransform, 1, 1, fit.crop);
        // Projected layers have no zone position: only their size changes (their centre stays on the garment point).
        if ('centerXmm' in layer.transform) {
          layer.transform.centerXmm += next.centerXmm;
          layer.transform.centerYmm += next.centerYmm;
        }
        layer.transform.widthMm = next.widthMm;
        layer.transform.heightMm = next.heightMm;
      }
    },
  };
}

/** Swap a placement for its lockup's layers, as ordinary layers where it was. One undo step. */
export function detachPlacement(zoneId: ArtboardId, layerId: string, layers: ArtworkLayer[]): Command {
  return {
    label: 'Detach from lockup',
    recipe: (d) => {
      const zone = stackOf(d, zoneId);
      if (!zone?.layers[layerId]) return;
      const at = zone.orderedLayerIds.indexOf(layerId);
      delete zone.layers[layerId];
      zone.orderedLayerIds.splice(at, 1);
      for (const layer of layers) zone.layers[layer.id] = structuredClone(layer);
      zone.orderedLayerIds.splice(at, 0, ...layers.map((l) => l.id));
    },
  };
}

